// TEST ONLY: explicitly opted-in matching host implementation, isolated Store.
// No application file edits, no browser access, no inference, no network.
import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,cp,mkdir,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {tmpdir} from 'node:os';
import {pathToFileURL,fileURLToPath} from 'node:url';
import {createRun} from '../native-engine.js';
import {loadData} from '../data.js';
const app=process.env.KURUMI_DISPLAY_HOST_APP,original=process.env.KURUMI_REAL_STORAGE;
test('installed plugin: actual HostContext / CanvasService first, replacement, lost memo, delete, invalid ID survives', {skip:!app||!original},async t=>{
 const hostImport=path=>import(pathToFileURL(join(app,path)).href);
 await hostImport('modules/plugins/sdk-loader.js');
 const {Store}=await hostImport('modules/agent/store.js');
 const {Runtime}=await hostImport('modules/agent/runtime.js');
 const {createHostContext}=await hostImport('modules/plugins/context.js');
 const root=await mkdtemp(join(tmpdir(),'kurumi-real-display-host-'));
 const store=new Store(join(root,'state'));
 const runtime=new Runtime(store,{piDir:join(root,'pi'),officialPluginsDirectory:join(root,'empty')});
 t.after(async()=>{await runtime.close();store.close();await rm(root,{recursive:true,force:true});});
 await runtime.init();
 const dataRoot=join(store.directory,'plugins','data','sesame','kurumi-replay');
 await mkdir(dataRoot,{recursive:true});
 await cp(join(original,'kurumi-data-v1'),join(dataRoot,'kurumi-data-v1'),{recursive:true,dereference:false});
 const data=await loadData(dataRoot);const engine=createRun('display-host-isolated',data.chapters,data.digests);
 store.put('plugin:sesame/kurumi-replay:challenge',{id:'continuous',revision:1,engine,commands:{},control:{running:false,remaining:0,active:null,attempt:0,phase:'paused'},model:null,roleTasks:[]});
 const draft=join(runtime.workspaces.root('conv_main'),'kurumi-replay');
 await cp(fileURLToPath(new URL('../',import.meta.url)),draft,{recursive:true,dereference:false});
 const checked=await runtime.plugins.manager.test('conv_main',{path:draft});assert.equal(checked.passed,true);
 const installed=await runtime.plugins.manager.install('conv_main',{path:draft,digest:checked.digest});
 assert.equal(installed.runtime_status,'ready');runtime.plugins.activate('conv_main',installed.id);
 const host=createHostContext(runtime,runtime.plugins.entry(installed.id),'conv_main');
 assert.throws(()=>host.storage.get('ui','audience-overlay'),e=>e.code==='not_found');
 assert.equal(host.storage.get('ui','audience-overlay',true),null);
 const invoke=async name=>(await runtime.plugins.definitions({conversationId:'conv_main'}).find(x=>x.name===name).execute('integration-'+name,{})).details;
 const first=await invoke('kurumi_display');assert.ok(first.instanceId);assert.equal(typeof first.overlay?.then,'undefined');
 const second=await invoke('kurumi_display');assert.notEqual(second.instanceId,first.instanceId);
 assert.equal(second.layout.charts.find(c=>c.id==='kurumi-h1').script_ids.length,1);
 host.storage.delete('ui','audience-overlay');
 const recovered=await invoke('kurumi_display');assert.notEqual(recovered.instanceId,second.instanceId);
 assert.equal(recovered.layout.charts.find(c=>c.id==='kurumi-h1').script_ids.length,1,'exact artifact ID/digest recovery does not duplicate');
 let scene=host.layout.inspect();await host.layout.apply({command_id:'display-host-delete-chart-0001',expected_version:scene.version,operations:[{op:'remove',id:'kurumi-h1'}]});
 const rebuilt=await invoke('kurumi_display');assert.notEqual(rebuilt.instanceId,recovered.instanceId);
 scene=host.layout.inspect();const artifact=scene.scripts.find(x=>x.id===rebuilt.instanceId).artifact;
 await assert.rejects(host.layout.script({action:'put',command_id:'display-host-bad-instance-0001',expected_version:scene.version,chart_id:'kurumi-h1',script_id:'nonexistent-instance',artifact,parameters:{}}),e=>e.code==='indicator_instance_mismatch');
 assert.equal((await invoke('kurumi_status')).state.balance,'300000');
 const final=await invoke('kurumi_display');assert.notEqual(final.instanceId,rebuilt.instanceId);
 assert.equal(final.layout.charts.find(c=>c.id==='kurumi-h1').script_ids.length,1);
 assert.equal((await invoke('kurumi_status')).state.decisions,0);
 console.log(JSON.stringify({layer:'actual-installed-host-not-browser',application:host.application,installedDigest:installed.digest,instances:[first,second,recovered,rebuilt,final].map(r=>r.instanceId),originalStorageReadOnly:true,paidRoleRequests:0,invalidInstanceErrorHandled:true}));
});
